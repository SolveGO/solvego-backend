package com.kdh.solvego.domain.payment.entity;

import com.kdh.solvego.domain.payment.type.PaymentStatus;
import com.kdh.solvego.domain.payment.type.PaymentType;
import com.kdh.solvego.domain.subscription.entity.Subscription;
import jakarta.persistence.*;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;

import java.time.Instant;

@Entity
@Table(name = "payments")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class Payment {

    // Internal database identifier for the payment.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "subscription_id")
    private Subscription subscription;

    // Order identifier generated by SolveGo and sent to the payment gateway.
    @Column(name = "order_id", nullable = false, unique = true, length = 64)
    private String orderId;

    // Payment identifier returned by the payment gateway after approval.
    @Column(name = "payment_key", unique = true, length = 200)
    private String paymentKey;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private PaymentType type;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private PaymentStatus status;

    @Column(nullable = false)
    private long amount;

    @Column(name = "order_name", nullable = false, length = 100)
    private String orderName = "SolveGO PRO 1개월";

    @Column(name = "renewal_cycle_at")
    private Instant renewalCycleAt;

    @Column(name = "failure_code", length = 100)
    private String failureCode;

    @CreationTimestamp
    @Column(name = "requested_at", nullable = false, updatable = false)
    private Instant requestedAt;

    @Column(name = "approved_at")
    private Instant approvedAt;

    @Column(name = "failed_at")
    private Instant failedAt;

    // Internal constructor used by factory methods to create payments
    // with a valid type and renewal cycle combination.
    private Payment(
            Subscription subscription,
            String orderId,
            PaymentType type,
            long amount,
            Instant renewalCycleAt
    ) {
        validateRenewalCycleAt(type, renewalCycleAt);

        this.subscription = subscription;
        this.orderId = orderId;
        this.type = type;
        this.status = PaymentStatus.READY;
        this.amount = amount;
        this.renewalCycleAt = renewalCycleAt;
    }

    private static void validateRenewalCycleAt(
            PaymentType type,
            Instant renewalCycleAt
    ) {
        if (type == PaymentType.RENEWAL && renewalCycleAt == null) {
            throw new IllegalArgumentException(
                    "renewalCycleAt is required for renewal payment"
            );
        }

        if (type == PaymentType.INITIAL && renewalCycleAt != null) {
            throw new IllegalArgumentException(
                    "renewalCycleAt must be null for initial payment"
            );
        }
    }

    // Creates an initial payment.
    // Initial payments do not belong to a renewal cycle.
    public static Payment initial(
            Subscription subscription,
            String orderId,
            long amount
    ) {
        return new Payment(
                subscription,
                orderId,
                PaymentType.INITIAL,
                amount,
                null
        );
    }

    // Creates a renewal payment for a specific renewal cycle.
    // A renewal payment must always have a renewal cycle timestamp.
    public static Payment renewal(
            Subscription subscription,
            String orderId,
            long amount,
            Instant renewalCycleAt
    ) {
        return new Payment(
                subscription,
                orderId,
                PaymentType.RENEWAL,
                amount,
                renewalCycleAt
        );
    }

    public void markProcessing() {
        this.status = PaymentStatus.PROCESSING;
    }

    public void markSucceeded(String paymentKey, Instant approvedAt) {
        this.paymentKey = paymentKey;
        this.status = PaymentStatus.SUCCEEDED;
        this.approvedAt = approvedAt;
        this.failureCode = null;
        this.failedAt = null;
    }

    public void markFailed(String failureCode, Instant failedAt) {
        this.status = PaymentStatus.FAILED;
        this.failureCode = failureCode;
        this.failedAt = failedAt;
    }

    public void markUnknown() {
        this.status = PaymentStatus.UNKNOWN;
    }

    public void markRefunded() {
        this.status = PaymentStatus.REFUNDED;
    }
}
